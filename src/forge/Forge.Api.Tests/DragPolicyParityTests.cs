namespace Forge.Api.Tests;

using System.Text.RegularExpressions;
using Forge.Api.Contracts;
using Forge.Api.Domain;
using Xunit;

/// <summary>
/// Drives the same scenarios as <c>policy.spec.ts</c> through the C# port
/// of <c>checkDragPolicy</c>. Field-by-field equality proves the two
/// implementations stay in lock-step.
///
/// We embed the scenarios inline rather than parsing the TS fixture file
/// at runtime — the fixture has structured comments and TypeScript-only
/// syntax that's not worth a tokenizer for one test class. If the TS
/// fixtures grow, swap to a JSON sidecar generated by <c>npm run build</c>.
/// </summary>
public class DragPolicyParityTests
{
    public static IEnumerable<object[]> Scenarios() => new[]
    {
        new object[] { "no-op (same column)", "design", "design", BaseCard("design"), Expected(allow: true) },
        new object[] { "forward by 1 — design → build", "design", "build", BaseCard("design"), Expected(allow: true, toast: "Moved to build") },
        new object[]
        {
            "forward by 1 — review → done with humanGate triggers confirm",
            "review", "done", GateCard(),
            Expected(allow: true, confirm: true,
                title: "Approve human-gated change?",
                text: "<strong>PR #240</strong> has been escalated for your review because: /security/ path requires human approval. Approving will merge to main."),
        },
        new object[] { "backward — build → backlog", "build", "backlog", BaseCard("build"), Expected(allow: true, toast: "Card moved back · agent reassigned") },
        new object[] { "backward from done — re-open warning", "done", "review", BaseCard("done"), Expected(allow: true, warn: "Re-open shipped item?", toast: "Item re-opened — agents will re-investigate") },
        new object[]
        {
            "skip-phase by 2 — backlog → build",
            "backlog", "build", BaseCard("backlog"),
            Expected(allow: true, confirm: true, title: "Skip phase?",
                text: "You're moving <strong>#100</strong> directly from <strong>backlog</strong> to <strong>build</strong>. This bypasses the 1 intermediate phase."),
        },
        new object[]
        {
            "skip-phase by 3 — backlog → review",
            "backlog", "review", BaseCard("backlog"),
            Expected(allow: true, confirm: true, title: "Skip phase?",
                text: "You're moving <strong>#100</strong> directly from <strong>backlog</strong> to <strong>review</strong>. This bypasses the 2 intermediate phases."),
        },
        new object[]
        {
            "bypass review — design → done",
            "design", "done", BaseCard("design"),
            Expected(allow: true, confirm: true, title: "Bypass review?",
                text: "You're marking <strong>#100</strong> as done without going through review. Code will not be reviewed by an agent and CI gates are skipped."),
        },
    };

    [Theory]
    [MemberData(nameof(Scenarios))]
    public void Matches_Typescript_Fixtures(string name, string from, string to, Card card, ExpectedPolicy expected)
    {
        var actual = DragPolicy.Check(from, to, card);

        Assert.Equal(expected.Allow, actual.Allow);
        Assert.Equal(expected.Confirm, actual.Confirm);
        Assert.Equal(expected.Title, actual.Title);
        Assert.Equal(expected.Text, actual.Text);
        Assert.Equal(expected.Warn, actual.Warn);
        Assert.Equal(expected.Toast, actual.Toast);
        _ = name;
    }

    [Fact]
    public void Fixture_File_Exists_On_Disk()
    {
        var fixturePath = Path.Combine(AppContext.BaseDirectory, "Fixtures", "policy.fixtures.ts");
        Assert.True(File.Exists(fixturePath), $"Expected fixture file to be copied to {fixturePath}");
        var content = File.ReadAllText(fixturePath);

        // Sanity: every scenario this file declares MUST appear by name in the TS fixtures.
        foreach (var row in Scenarios())
        {
            var name = (string)row[0];
            Assert.True(content.Contains(name, StringComparison.Ordinal),
                $"Scenario '{name}' not found in TS fixture file. Update both sides together.");
        }

        _ = Regex.IsMatch(content, "policyScenarios"); // shape probe
    }

    public sealed record ExpectedPolicy(
        bool Allow, bool Confirm, string? Title, string? Text, string? Warn, string? Toast);

    private static ExpectedPolicy Expected(bool allow, bool confirm = false, string? title = null, string? text = null, string? warn = null, string? toast = null)
        => new(allow, confirm, title, text, warn, toast);

    private static Card BaseCard(string col) => new(
        Id: "#100", Epic: "EPIC-024", Col: col, Type: "story", Title: "parity sample",
        Tags: Array.Empty<string>(), Pts: 3, Priority: "med", Agent: null, Cost: 0);

    private static Card GateCard() => BaseCard("review") with
    {
        Id = "PR #240",
        HumanGate = true,
        GateReason = "/security/ path requires human approval",
    };
}
