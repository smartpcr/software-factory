import { describe, expect, it } from 'vitest';
import { renderMarkdown } from './markdown';

describe('renderMarkdown', () => {
  it('renders headings 1..3', () => {
    expect(renderMarkdown('# Hello')).toBe('<h1>Hello</h1>');
    expect(renderMarkdown('## What changed')).toBe('<h2>What changed</h2>');
    expect(renderMarkdown('### Evaluator Review')).toBe('<h3>Evaluator Review</h3>');
  });

  it('renders bullet lists, coalescing adjacent items', () => {
    const md = '- Atomic volatile writes\n- ETW instrumentation\n- 5 config params';
    const html = renderMarkdown(md);
    expect(html).toBe(
      '<ul><li>Atomic volatile writes</li><li>ETW instrumentation</li><li>5 config params</li></ul>',
    );
  });

  it('renders inline bold + code on a single line', () => {
    const html = renderMarkdown('**Work Item:** WI-37738500 (`ADO #37738500`)');
    expect(html).toContain('<strong>Work Item:</strong>');
    expect(html).toContain('<code>ADO #37738500</code>');
  });

  it('preserves paragraph breaks across blank lines', () => {
    const md = 'First paragraph.\n\nSecond paragraph.';
    expect(renderMarkdown(md)).toBe('<p>First paragraph.</p>\n<p>Second paragraph.</p>');
  });

  it('escapes raw HTML so <script> can never execute', () => {
    const html = renderMarkdown('<script>alert(1)</script>');
    expect(html).not.toContain('<script>');
    expect(html).toContain('&lt;script&gt;');
  });

  it('renders the full PR description shape (heading + bullets + bold)', () => {
    // Mirrors the actual ADO description shape from the user's screenshot.
    const md = [
      '## Implement circuit breaker policy in update service - round 2 with design doc',
      '',
      '**Work Item:** WI-37738500 (ADO #37738500)',
      '**Score:** 92 | **Iterations:** 3',
      '',
      '### What changed',
      '- Atomic volatile writes for .NET Framework compatibility',
      '- ETW instrumentation for all major events',
      '- 5 configuration parameters read dynamically',
      '',
      '---',
      '*Auto-generated by Forge.*',
    ].join('\n');
    const html = renderMarkdown(md);

    expect(html).toContain('<h2>Implement circuit breaker policy in update service - round 2 with design doc</h2>');
    expect(html).toContain('<h3>What changed</h3>');
    expect(html).toContain('<strong>Work Item:</strong>');
    expect(html).toContain('<strong>Score:</strong>');
    expect(html).toContain('<li>Atomic volatile writes for .NET Framework compatibility</li>');
    expect(html).toContain('<li>5 configuration parameters read dynamically</li>');
    expect(html).toContain('<hr/>');
    expect(html).toContain('<em>Auto-generated by Forge.</em>');
  });
});
