import type { PrComment } from '@/types';

// Phase 28.2 — shared classifier for "is this PR comment actually a
// build/CI event?". Used by PrCommentsList to *exclude* these from the
// review-conversation view, and by PrBuildsList to *include* them in
// the builds tab.
//
// Why we can't just check authorKind === 'system': ADO PR pipelines
// post their status as plain `text` comments under a service-account
// identity (often with an empty UPN), so they arrive with
// authorKind='human'. They have very recognisable body markers
// (`@@@ci1`, `Pipeline: [...]`, `voted -10`, etc.) that we sniff for
// instead of guessing from the author.

const CI_PIPELINE_PREFIX = /^@@@ci\d+/i;
const PIPELINE_LINE = /Pipeline:\s*\[/i;
const VOTE_LINE = /\bvoted\s+-?\d+\b/i;
const POLICY_LINE = /^Policy status has been updated$/i;
const REF_UPDATED = /reference\s+refs?\/heads\//i;
const AUTO_COMPLETE = /set\s+auto[-\s]?complete/i;
const REVIEWER_ADDED = /added\s+\d+\s+reviewers?/i;
const PR_ASSISTANT = /<span[^>]*>\s*PR Assistant\s*<\/span>/i;
const DECLINED_REVIEW = /declined to review/i;

/**
 * Returns true when the comment is generated by automation (CI build
 * pipeline, build voting, ref-update notification, policy change)
 * rather than a review remark.
 *
 * Carve-out: ADO's "PR Assistant" / GitOps AI Code Review remarks
 * arrive as `authorKind: 'system'` because their service account
 * posts with `commentType=system`, but they're actual code-review
 * feedback (with severity, suggested code, file:line refs). We
 * surface them in the Comments tab via {@link isAgentReview}.
 *
 * The body-pattern fallback only fires when the author UPN is empty —
 * ADO's pipelines post under a service account with no UPN, while a
 * real reviewer always has a populated `authorId`. This avoids
 * misclassifying a real review comment that happens to mention the
 * word "voted" or links to a Pipeline page.
 */
export function isBuildEvent(c: PrComment): boolean {
  const body = (c.body ?? '').trim();
  if (isAgentReview(c)) return false;
  if (c.authorKind === 'system') return true;
  const authorMissing = !c.authorId || c.authorId.length === 0;
  if (!authorMissing) return false;
  if (!body) return false;
  return CI_PIPELINE_PREFIX.test(body)
    || PIPELINE_LINE.test(body)
    || VOTE_LINE.test(body)
    || POLICY_LINE.test(body)
    || REF_UPDATED.test(body)
    || AUTO_COMPLETE.test(body)
    || REVIEWER_ADDED.test(body)
    || DECLINED_REVIEW.test(body);
}

/**
 * Returns true for AI / bot review remarks that should appear in the
 * Comments tab — currently the ADO "PR Assistant" / GitOps AI Code
 * Review bodies. These have `<span>PR Assistant</span>` as their
 * header followed by tag pills (severity / area / iteration) and
 * the actual remark content.
 */
export function isAgentReview(c: PrComment): boolean {
  const body = (c.body ?? '').trim();
  if (!body) return false;
  return PR_ASSISTANT.test(body);
}

export type BuildEventKind = 'ci-pipeline' | 'vote' | 'ref' | 'auto-complete' | 'policy' | 'reviewers' | 'assistant' | 'other';

export type CiStatus = 'running' | 'failed' | 'succeeded' | 'queued' | 'cancelled' | 'unknown';

/**
 * Top-level grouping for the PR detail panel's automation tabs:
 *   - `build`  — pipeline runs and build-service vote events.
 *   - `change` — ref / branch-update notifications.
 *   - `policy` — auto-complete, ownership / reviewer policy, and ADO
 *     policy-status updates.
 *
 * Mirrors the way the ADO web UI segments the same notifications.
 */
export type AutomationCategory = 'build' | 'change' | 'policy';

/** Maps a {@link BuildEventKind} onto its tab category. */
export function automationCategory(kind: BuildEventKind): AutomationCategory {
  switch (kind) {
    case 'ci-pipeline':
    case 'vote':
      return 'build';
    case 'ref':
      return 'change';
    case 'auto-complete':
    case 'policy':
    case 'reviewers':
      return 'policy';
    default:
      return 'build';
  }
}

export interface ClassifiedBuildEvent {
  kind: BuildEventKind;
  /** Short, human-readable label for the collapsed row. Already stripped of HTML/markdown. */
  name: string;
  /** Optional vote score parsed out of "voted -10" style bodies. */
  vote?: number;
  /** Voter / reviewer display name parsed out of "X voted N" bodies. */
  voter?: string;
  /** Optional pipeline run number parsed out of `@@@ci{N}` markers. */
  ciRunIndex?: number;
  /** Pipeline display name (e.g. "AzSCI_E2E_PR_Bot") parsed from the
   *  CI body, used to populate the "filter by build" chips. */
  pipelineName?: string;
  /** Latest pipeline status pulled from the most recent `**[date]**`
   *  block in the body. ADO's CI bot accumulates messages in the
   *  same thread as the pipeline progresses, so the FIRST entry in
   *  the body holds the current state. */
  ciStatus?: CiStatus;
}

const CI_STATUS_PHRASES: Array<{ re: RegExp; status: CiStatus }> = [
  { re: /has\s+failed/i,                          status: 'failed' },
  { re: /has\s+succeeded|has\s+passed/i,          status: 'succeeded' },
  { re: /started\s+running|is\s+running/i,        status: 'running' },
  { re: /queued|waiting/i,                        status: 'queued' },
  { re: /cancell?ed|disabled|removing\s+reviewer/i, status: 'cancelled' },
];

/** Reads the first `**[Iteration N]** <status>` line out of a CI body
 *  and returns the status keyword. ADO accumulates pipeline messages
 *  newest-first, so the head of the body is the live state. */
export function parseCiStatus(body: string): CiStatus {
  const m = /\*\*\[Iteration[^\]]*\]\*\*\s*([^\n]+)/i.exec(body);
  const phrase = m?.[1] ?? '';
  for (const { re, status } of CI_STATUS_PHRASES) {
    if (re.test(phrase)) return status;
  }
  return 'unknown';
}

/**
 * Strip HTML tags + markdown control characters and collapse whitespace
 * into a single line, then truncate. Used for the collapsed-row label
 * so we never leak `<span style="…">` markup into a button caption.
 *
 * Drops `<small>` blocks first — ADO's PR Assistant uses them for the
 * AI Code Review / Severity / Iteration tag pills, which would
 * otherwise drown out the actual review remark in the row title.
 */
export function summarizePlainText(body: string | null | undefined, max = 90): string {
  if (!body) return '';
  const text = body
    .replace(/<small[\s\S]*?<\/small>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/[#>*_`~]/g, '')
    .replace(/\\r/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!text) return '';
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

/**
 * Inspect a comment body and pick a friendly name + kind for the row.
 * Falls back to a one-line plain-text summary when nothing matches.
 */
export function classifyBuildEvent(c: PrComment): ClassifiedBuildEvent {
  const body = (c.body ?? '').trim();

  const ci = /^@@@ci(\d+)/i.exec(body);
  if (ci) {
    const idx = Number.parseInt(ci[1], 10);
    // Try to extract pipeline name from `Pipeline: [Name :link:](url)`.
    const pipeline = /Pipeline:\s*\[([^\]:]+)/i.exec(body);
    const pipelineName = pipeline ? pipeline[1].trim() : undefined;
    const ciStatus = parseCiStatus(body);
    const name = pipelineName ?? `Pipeline run #${idx}`;
    return { kind: 'ci-pipeline', name, ciRunIndex: idx, pipelineName, ciStatus };
  }

  const vote = /^(.+?)\s+voted\s+(-?\d+)/i.exec(body);
  if (vote) {
    const voter = vote[1].trim();
    const score = Number.parseInt(vote[2], 10);
    return {
      kind: 'vote',
      name: voter,
      voter,
      vote: Number.isFinite(score) ? score : undefined,
    };
  }

  if (REF_UPDATED.test(body)) return { kind: 'ref', name: 'Branch updated' };
  if (AUTO_COMPLETE.test(body)) return { kind: 'auto-complete', name: summarizePlainText(body, 80) || 'Auto-complete set' };
  if (POLICY_LINE.test(body)) return { kind: 'policy', name: 'Policy status updated' };
  if (REVIEWER_ADDED.test(body)) return { kind: 'reviewers', name: summarizePlainText(body, 80) };
  if (PR_ASSISTANT.test(body)) {
    const text = summarizePlainText(body, 80);
    return { kind: 'assistant', name: text || 'PR Assistant note' };
  }
  if (DECLINED_REVIEW.test(body)) return { kind: 'vote', name: summarizePlainText(body, 60) };

  return { kind: 'other', name: summarizePlainText(body, 80) || '(no content)' };
}
