namespace Forge.Api.Services.Stories.Templates;

using System;
using System.Collections.Generic;

/// <summary>
/// docs/forge/e2e.md Stage 7.3 — Go / godog counterpart of
/// <see cref="E2eBaseRenderer"/>. For a Go repository the qa-e2e harness is
/// godog (Cucumber-for-Go): Gherkin <c>.feature</c> files + <c>*_test.go</c>
/// step definitions run by <c>go test -tags e2e</c>. There is no
/// <c>appsettings.e2e.json</c> (Go reads secrets straight from the
/// environment), so this renderer emits two deterministic, framework-shaped
/// files instead:
///
/// <list type="bullet">
///   <item><c>test/e2e/.gitignore</c> — a directory-scoped ignore so a Go
///         test build never lands compiled test binaries / cached output in
///         a PR. Always emitted (additive — never clobbers the repo-root
///         <c>.gitignore</c>).</item>
///   <item><c>test/e2e/{storyId}/e2ebase.go</c> — a build-tagged
///         (<c>//go:build e2e</c>) <c>package e2e</c> file with a
///         <c>RequireEnv</c> helper that skips a scenario when a required
///         env-var is unset. Per-spawn (emitted by the first qa-e2e
///         workstream to fire; the strategy tracks "first-per-spawn" and
///         passes <paramref name="includeBaseClass"/>=true only then —
///         this renderer is pure).</item>
/// </list>
///
/// <para>All step-def files for a story live in the single directory
/// <c>test/e2e/{storyId}/</c> as <c>package e2e</c>, so they share this
/// <c>RequireEnv</c> helper with no import. The companion generator prompt
/// (<c>CrewStoryArtifactStrategy.BuildQaE2eGeneratorTask</c>) names each
/// stage's initializer / test entrypoint uniquely to avoid symbol
/// collisions inside that shared package.</para>
/// </summary>
public static class GoE2eBaseRenderer
{
    /// <summary>docs/forge/e2e.md Stage 7.3 — directory-scoped ignore path.</summary>
    public static string GitignorePathFor() => "test/e2e/.gitignore";

    /// <summary>docs/forge/e2e.md Stage 7.3 — per-spawn Go base helper path.</summary>
    public static string E2eBasePathFor(string storyId) =>
        $"test/e2e/{StoryPaths.Safe(storyId)}/e2ebase.go";

    /// <summary>
    /// docs/forge/e2e.md Stage 7.3 — render the directory-scoped
    /// <c>.gitignore</c> covering Go test/build artifacts so a
    /// <c>go test</c> run never leaks compiled binaries into the PR.
    /// </summary>
    public static string RenderGitignore() =>
        """
        # Forge — generated. Go test/build artifacts that must not be committed.
        *.test
        *.out
        __debug_bin*

        """;

    /// <summary>
    /// docs/forge/e2e.md Stage 7.3 — render the per-spawn <c>e2ebase.go</c>
    /// shared-helper file. Build-tagged so it compiles only under
    /// <c>go test -tags e2e</c>, matching the step-def files.
    /// </summary>
    public static string RenderE2eBaseFile(string storyId) =>
        $$"""
        //go:build e2e

        // Code generated by Forge for story '{{storyId}}' — DO NOT EDIT.
        // docs/forge/e2e.md Stage 7.3 (Go / godog variant). Shared helpers for
        // the godog step-definition files in this package. Emitted ONCE per
        // spawn (by the first qa-e2e workstream to fire); subsequent qa-e2e
        // stages reuse this file. The generator regenerates it on the next
        // full Forge spawn.

        package e2e

        import (
        	"os"
        	"testing"
        )

        // RequireEnv returns the value of the named environment variable, or
        // skips the calling test when it is unset/empty. Locally (no secret
        // store) the scenario yellow-skips; on CI the secret store populates
        // the var, so a skip there signals a genuinely missing secret rather
        // than an expected local skip.
        func RequireEnv(t *testing.T, name string) string {
        	t.Helper()
        	v := os.Getenv(name)
        	if v == "" {
        		t.Skipf("E2E setup skipped: required env var %q is not set; populate it via the CI secret store.", name)
        	}
        	return v
        }

        """;

    /// <summary>
    /// docs/forge/e2e.md Stage 7.3 — render the deterministic Go qa-e2e
    /// scaffold files. Mirrors <see cref="E2eBaseRenderer.RenderAll"/>'s
    /// signature so <c>CrewStoryArtifactStrategy.ProduceStageE2eAsync</c> can
    /// switch on ecosystem without branching its merge logic. The
    /// <paramref name="phaseSlug"/> / <paramref name="setupType"/> parameters
    /// are accepted for signature parity (Go has no per-phase appsettings
    /// file); only the per-spawn base file is produced here. The scoped
    /// <c>.gitignore</c> is folded in by the caller via
    /// <see cref="GitignorePathFor"/> / <see cref="RenderGitignore"/>.
    /// </summary>
    public static IReadOnlyDictionary<string, string> RenderAll(
        string storyId, string phaseSlug, E2eSetupType setupType, bool includeBaseClass)
    {
        _ = phaseSlug;
        _ = setupType;
        var dict = new Dictionary<string, string>(StringComparer.Ordinal);
        if (includeBaseClass)
        {
            dict[E2eBasePathFor(storyId)] = RenderE2eBaseFile(storyId);
        }
        return dict;
    }
}
